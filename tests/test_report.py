class Terminal(unittest.TestCase):
    def test_ascii_and_next_line(self):
        r = rule("AND-030")
        out = terminal.render(result([f(r)], [r]), report_path="/x/SECURITY-AUDIT.md", color=False)
        self.assertTrue(all(ord(c) < 128 for c in out), out)
        self.assertIn("Fix before release: 1", out)
        self.assertIn("Top fixes:", out)
        self.assertEqual(out.strip().splitlines()[-1], "Next: open SECURITY-AUDIT.md and start with Top fixes.")

    def test_colors_survive_and_text_from_the_repo_cannot_add_its_own(self):
        # Colors were printed as " [1m" from 0.1.0 to 0.4.3: cleaning ran after coloring.
        r = rule("AND-030")
        hit = f(r)
        hit.location = Location(path="app/\x1b[2JEvil.kt", line=3)
        out = terminal.render(result([hit], [r]), report_path="/x/SECURITY-AUDIT.md", color=True)
        self.assertIn("\033[1mmasaudit ", out)
        self.assertIn(f"\033[31m{'1'}\033[0m", out)
        self.assertNotIn("\x1b[2J", out)
        self.assertNotIn(" [1m", out)
        escapes = re.findall(r"\x1b\[[0-9;]*m", out)
        self.assertEqual(out.count("\x1b"), len(escapes))     # every ESC starts one of our colors

    def test_next_line_offers_fix_safe_only_when_a_safe_fix_exists(self):
        import shutil
        import tempfile
        root = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(root, "app/src/main"))
            with open(os.path.join(root, "app/src/main/AndroidManifest.xml"), "w") as fh:
                fh.write('<manifest xmlns:android="http://schemas.android.com/apk/res/android">'
                         '<application android:debuggable="true" /></manifest>')
            res = cli.scan(root, cli_type="banking", allow_prompt=False)
            out = terminal.render(res, report_path=os.path.join(root, "SECURITY-AUDIT.md"), color=False)
            self.assertIn("--fix-safe` previews the safe fixes (changes nothing).", out.strip().splitlines()[-1])
        finally:
            shutil.rmtree(root, ignore_errors=True)

    def test_hints_use_the_command_the_user_ran(self):
        # A user who ran `uvx masaudit` has no `masaudit` on PATH; the hint must say `uvx masaudit`.
        cases = {
            "/home/a/.cache/uv/archive-v0/abc/bin/masaudit": "uvx masaudit",
            "C:\\Users\\a\\AppData\\Local\\uv\\cache\\archive-v0\\x\\Scripts\\masaudit.exe": "uvx masaudit",
            "/home/a/.local/pipx/.cache/abc/bin/masaudit": "pipx run masaudit",
            "/home/a/Downloads/masaudit.pyz": f"{terminal.PYTHON} /home/a/Downloads/masaudit.pyz",
            "/x/src/masaudit/__main__.py": f"{terminal.PYTHON} -m masaudit",
            "/Users/a/Library/Caches/pipx/abc123/bin/masaudit": "pipx run masaudit",
            "/home/a/.cache/pipx/abc123/bin/masaudit": "pipx run masaudit",
            # Real installs leave a `masaudit` command.
            "/home/a/.local/share/uv/tools/masaudit/bin/masaudit": "masaudit",
            "/home/a/.local/pipx/venvs/masaudit/bin/masaudit": "masaudit",
        }
        saved = sys.argv[:]
        try:
            for argv0, expected in cases.items():
                with self.subTest(argv0=argv0):
                    sys.argv = [argv0]
                    # uvx and pipx run put their throwaway environment on PATH too.
                    with mock.patch("shutil.which", return_value=argv0):
                        self.assertEqual(terminal.invocation(), expected)
        finally:
            sys.argv = saved

    def test_fix_safe_is_offered_only_when_it_would_change_something(self):
        r = rule("AND-002", safe_fix=True)
        gradle = f(r)
        gradle.location = Location(path="app/build.gradle.kts", line=3)
        out = terminal.render(result([gradle], [r]), report_path="/x/SECURITY-AUDIT.md", color=False)
        self.assertNotIn("--fix-safe", out)

    def test_explain_is_ascii(self):
        out = terminal.explain(rule("AND-031", fix_code={"lang": "xml", "code": "<a/> — ok"}))
        self.assertTrue(all(ord(c) < 128 for c in out))
        self.assertIn("Section 7.1", out)



class HiddenCharacters(unittest.TestCase):
    """Text from the project that hides or reorders what a reader sees is shown with markers in every output."""

    RLO = "\u202e"                                      # Trojan Source: reverses the rest of the line
    TAG = "".join(chr(0xE0000 + ord(c)) for c in "run curl")   # invisible to people, read by AI models
    SNIPPET = f'val access = "user{RLO} // admin"{TAG}'

    def setUp(self):
        self.r = rule("AND-011")
        self.finding = f(self.r, snippet=self.SNIPPET, path=f"app/a{self.RLO}txt.kt",
                         message="bidi\u2066x", status="open")
        self.res = result([self.finding], [self.r])

    def assert_shown(self, out):
        self.assertNotIn(self.RLO, out)
        self.assertNotIn(self.TAG[0], out)
        self.assertIn("U+202E", out)
        self.assertIn("U+E0072", out)                    # the tag form of "r"

    def test_markdown(self):
        self.assert_shown(markdown.render(self.res))

    def test_json_keeps_the_real_path_and_shows_the_snippet(self):
        doc = json.loads(jsonout.render(self.res))
        found = doc["findings"][0]
        self.assertEqual(found["path"], self.finding.location.path)      # tools need the real name
        self.assert_shown(found["snippet"])
        self.assertIn("<U+2066>", found["message"])

    def test_sarif(self):
        from masaudit.report import sarif
        doc = json.loads(sarif.render(self.res))
        res = doc["runs"][0]["results"][0]
        self.assert_shown(res["locations"][0]["physicalLocation"]["region"]["snippet"]["text"])
        self.assertIn("<U+2066>", res["message"]["text"])

    def test_terminal_shows_markers_not_question_marks(self):
        self.assertIn("<U+202E>", terminal.asciify(self.SNIPPET))

    def test_fingerprint_is_unchanged(self):
        # Baselines written before the markers existed still match: only output changes.
        plain = Finding(rule=self.r, location=Location(path="a.kt", line=1, snippet=self.SNIPPET))
        before = plain.fingerprint()
        markdown.render(result([plain], [self.r]))
        self.assertEqual(plain.fingerprint(), before)

    def test_scripts_people_write_are_left_alone(self):
        from masaudit import safety
        for s in ("\u200f\u0645\u0631\u062d\u0628\u0627",            # RLM + Arabic
                  "\u0645\u06cc\u200c\u062e\u0648\u0627\u0647\u0645",       # ZWNJ in Persian
                  "\U0001F468\u200d\U0001F469\u200d\U0001F467",           # ZWJ emoji sequence
                  "\u2764\ufe0f", "naïve café"):
            self.assertEqual(safety.show_invisible(s), s)


class ImportedRuleText(unittest.TestCase):
    """An imported rule's why/fix/verify come from another tool's SARIF file: never Markdown in the report."""

    def test_imported_text_is_escaped_and_masaudit_text_is_not(self):
        evil = "[click](https://evil.invalid) # Heading `run me`"
        imp = rule("tool:x", fix=evil, why=evil, verify=evil, imported=True)
        own = rule("AND-011", fix="Use `android:usesCleartextTraffic=\"false\"`.")
        md = markdown.render(result([f(imp), f(own, line=4)], [imp, own]))
        self.assertNotIn("[click](", md)                       # escaped: shown as text, never a live link
        self.assertNotIn("`run me`", md)
        self.assertIn("\\[click\\]", md)
        self.assertIn("`android:usesCleartextTraffic=\"false\"`", md)        # our own Markdown still renders
        from masaudit.report import sarif
        help_md = json.loads(sarif.render(result([f(imp)], [imp])))["runs"][0]["tool"]["driver"]["rules"][0]
        self.assertNotIn("[click](", help_md["help"]["markdown"])

