"""Regenerate every derived file from the rules and the scanner. CI fails if they're stale.

    python3 scripts/generate.py

Writes:
  plugin/skills/masaudit/scripts/masaudit.pyz      bundled offline scanner for the skill
  plugin/skills/masaudit/references/rules.md       every rule, for the AI assistant
  plugin/skills/masaudit/references/fixes-*.md     paste-ready fixes by platform (MIT-0)
  docs/rules.md                                    the same rule catalog for humans
  docs/sample-report-banking.md / -news.md         the demo app scanned under two profiles
"""

from __future__ import annotations

import os
import subprocess
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from masaudit import engine  # noqa: E402

SKILL = os.path.join(ROOT, "plugin", "skills", "masaudit")
DEMO = os.path.join(ROOT, "examples", "acme-wallet")
EPOCH = "1767225600"   # 2026-01-01: fixed so generated reports are reproducible

PLATFORM_NAMES = {"android": "Android", "ios": "iOS", "kmp": "Kotlin Multiplatform", "flutter": "Flutter",
                  "cross": "Cross-platform code", "ci": "CI and supply chain"}
FIX_FILES = {"android": "fixes-android.md", "ios": "fixes-ios.md", "kmp": "fixes-kmp.md", "ci": "fixes-ci.md"}
LANG_TO_PLATFORM = {"kotlin": "android", "java": "android", "xml": "android", "groovy": "android",
                    "swift": "ios", "objc": "ios", "yaml": "ci"}


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def rule_block(r, heading: str = "###") -> str:
    ids = " · ".join(x for x in [r.maswe, r.masvs] + list(r.mastg) if x)
    lines = [
        f"{heading} {r.id}: {r.title}",
        "",
        f"**Severity:** {r.severity} · **Profiles:** {', '.join('MAS-' + p for p in r.profiles)}"
        f" · **Confidence:** {r.confidence} · **Effort:** {r.effort}"
        + (f" · **Only for:** {', '.join(r.app_types)}" if r.app_types else ""),
        "",
        f"**Why it matters:** {r.why}",
        "",
        f"**Fix:** {r.fix}",
        "",
        f"**Verify:** {r.verify}",
        "",
    ]
    if r.app_types:
        lines += [f"**Other apps:** {r.not_needed_reason}", ""]
    if ids:
        lines += [f"**IDs:** {ids}", ""]
    lines += [f"**Read more:** [book {r.book}]({r.book_url})", ""]
    return "\n".join(lines)


def catalog(rules) -> str:
    by_platform = defaultdict(list)
    for r in rules:
        if not r.retired:
            by_platform[r.platform].append(r)
    out = [
        "# masaudit rules",
        "",
        "<!-- Generated by scripts/generate.py from src/masaudit/rules/*.json. Don't edit by hand. -->",
        "",
        f"Rules version {engine.rules_version()}, {sum(len(v) for v in by_platform.values())} rules. "
        "Severity applies when the app's profile includes the rule's MAS profiles; otherwise the "
        "finding is listed under \"Not needed for your app\". Fix snippets are MIT-0; explanations "
        "are adapted from the book (CC BY-SA 4.0).",
        "",
        "| ID | Title | Severity | Profiles |",
        "|---|---|---|---|",
    ]
    for platform in PLATFORM_NAMES:
        for r in by_platform.get(platform, []):
            out.append(f"| [{r.id}](#{r.id.lower()}-{_slug(r.title)}) | {r.title} | {r.severity} | "
                       f"{', '.join(r.profiles)} |")
    out.append("")
    for platform, name in PLATFORM_NAMES.items():
        if not by_platform.get(platform):
            continue
        out += [f"## {name}", ""]
        out += [rule_block(r) for r in by_platform[platform]]
    return "\n".join(out).rstrip() + "\n"


def fixes(rules) -> dict:
    files = {name: [] for name in FIX_FILES.values()}
    for r in rules:
        if r.retired or not r.fix_code:
            continue
        platform = r.platform
        if platform == "cross":
            platform = LANG_TO_PLATFORM.get(r.fix_code.get("lang", ""), "android")
        target = FIX_FILES.get(platform)
        if not target:
            continue
        files[target].append(
            f"## {r.id}: {r.title}\n\n{r.fix}\n\n```{r.fix_code.get('lang', 'text')}\n"
            f"{r.fix_code['code'].rstrip()}\n```\n\nVerify: {r.verify}\n\nBook: [{r.book}]({r.book_url})\n"
        )
    out = {}
    for name, blocks in files.items():
        title = {"fixes-android.md": "Android", "fixes-ios.md": "iOS", "fixes-kmp.md": "Kotlin Multiplatform",
                 "fixes-ci.md": "CI and supply chain"}[name]
        out[name] = (
            f"# Paste-ready fixes: {title}\n\n"
            "<!-- Generated by scripts/generate.py. Don't edit by hand. -->\n\n"
            "These snippets are released under MIT-0: use them in any app, no attribution needed. "
            "Adapt names to the project, keep the logic.\n\n"
            + ("\n".join(blocks) if blocks else "No fixes for this platform yet.\n")
        )
    return out


def _slug(text: str) -> str:
    import re
    t = re.sub(r"[^\w\- ]", "", text.lower())
    return t.replace(" ", "-")


def main() -> None:
    rules = engine.load_rules()
    cat = catalog(rules)
    write(os.path.join(ROOT, "docs", "rules.md"), cat)
    write(os.path.join(SKILL, "references", "rules.md"), cat)
    for name, text in fixes(rules).items():
        write(os.path.join(SKILL, "references", name), text)

    subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "build_zipapp.py"),
                    "--output", os.path.join(SKILL, "scripts", "masaudit.pyz")], check=True,
                   env={**os.environ, "SOURCE_DATE_EPOCH": EPOCH})

    if os.path.isdir(DEMO):
        import shutil
        import tempfile

        env = {**os.environ, "PYTHONPATH": os.path.join(ROOT, "src"), "SOURCE_DATE_EPOCH": EPOCH}
        # Scan a copy: under examples/ every file would count as sample code and be downgraded.
        with tempfile.TemporaryDirectory() as tmp:
            demo = os.path.join(tmp, "acme-wallet")
            shutil.copytree(DEMO, demo)
            for app_type, name in (("banking", "sample-report-banking.md"), ("news", "sample-report-news.md")):
                out = os.path.join(ROOT, "docs", name)
                subprocess.run([sys.executable, "-m", "masaudit", demo, "--app-type", app_type,
                                "--format", "md", "--output", out], check=False, env=env,
                               cwd=tmp, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL)
                print("wrote", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    main()
